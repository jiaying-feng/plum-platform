# -*- coding: utf-8 -*-
"""
Bundle a lightweight, offline copy of the business photos into the mini program.

Why: on a real phone `local` (127.0.0.1) points at the phone itself, and `lan`
uses plain HTTP which the WeChat runtime blocks without debug mode. Keeping the
photos inside the package makes the default `mock` environment show real images
with zero network requests, on developer tools and on phones alike.

    python tools/build_mp_photos.py
    -> mp-weixin/images/photos/*.jpg
    -> mp-weixin/utils/photos.js   (generated manifest, do not hand-edit)
"""
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets"
OUT = ROOT / "mp-weixin" / "images" / "photos"
MANIFEST = ROOT / "mp-weixin" / "utils" / "photos.js"

MAX_EDGE = 420
QUALITY = 70
EXTS = {".webp", ".png", ".jpg", ".jpeg"}


def group_of(stem):
    if stem.startswith("banner"):
        return "banner"
    if stem.startswith("orchard"):
        return "orchard"
    if stem.startswith("homestay"):
        return "homestay"
    if stem.startswith("research"):
        return "research"
    return "product"


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    groups = {"banner": [], "orchard": [], "homestay": [], "research": [], "product": []}
    names = []
    total = 0

    for src in sorted(SRC.iterdir()):
        if src.suffix.lower() not in EXTS:
            continue
        stem = src.stem
        im = Image.open(src).convert("RGB")
        im.thumbnail((MAX_EDGE, MAX_EDGE), Image.Resampling.LANCZOS)
        dst = OUT / (stem + ".jpg")
        im.save(dst, "JPEG", quality=QUALITY, optimize=True, progressive=True)
        total += dst.stat().st_size
        names.append(stem)
        groups[group_of(stem)].append(stem)

    def js_list(items):
        return "[\n" + "".join("    '%s',\n" % n for n in items) + "  ]"

    body = """/* AUTO-GENERATED by tools/build_mp_photos.py - do not edit by hand.
 * Package-local photos. These travel inside the mini program, need no network,
 * no domain whitelist and no HTTPS, so mock mode looks the same on a phone.
 */
const FILES = __FILES__;

const GROUPS = {
__GROUPS__
};

/** /assets/foo.webp -> /images/photos/foo.jpg, or '' when not bundled. */
function bundled(path) {
  const name = String(path || '').split('/').pop().split('?')[0].replace(/\\.[^.]+$/, '');
  return FILES.indexOf(name) >= 0 ? '/images/photos/' + name + '.jpg' : '';
}

/** Infer the photo category from the shape of a business record. */
function groupOf(item) {
  const it = item || {};
  if (it.festival_date || it.place) return 'banner';
  if (it.start_date) return 'research';
  if (it.rooms) return 'homestay';
  if (it.spot_type || it.badge) return 'orchard';
  if (it.adult_price !== undefined || it.child_price !== undefined) return 'orchard';
  if (it.price !== undefined) return 'product';
  return 'banner';
}

/** Stable offline photo for one record; falls back by category when image is empty. */
function pick(item, index) {
  const local = bundled(item && item.image);
  if (local) return local;
  const list = GROUPS[groupOf(item)] || GROUPS.banner;
  const i = Math.abs(Number(index) || 0) % list.length;
  return '/images/photos/' + list[i] + '.jpg';
}

module.exports = { FILES, GROUPS, bundled, groupOf, pick };
"""
    groups_js = "".join("  %s: %s,\n" % (k, js_list(v).replace("\n", "\n  "))
                        for k, v in groups.items())
    body = body.replace("__FILES__", js_list(names)).replace("__GROUPS__", groups_js.rstrip("\n"))
    MANIFEST.write_text(body, encoding="utf-8")
    print("photos  : %d files, %d bytes total" % (len(names), total))
    print("manifest:", MANIFEST)
    print("groups  :", {k: len(v) for k, v in groups.items()})


if __name__ == "__main__":
    main()
